import { readFile, writeFile } from "node:fs/promises";
const sourceUrl = new URL("../src/data/redirects.json", import.meta.url);
const outputUrl = new URL("../public/_redirects", import.meta.url);
const redirects = JSON.parse(await readFile(sourceUrl, "utf8"));
const seen = new Set();
for (const redirect of redirects) {
  if (!redirect.from?.startsWith("/") || !redirect.to?.startsWith("/") || redirect.status !== 301) throw new Error(`Invalid redirect: ${JSON.stringify(redirect)}`);
  if (redirect.from === redirect.to || seen.has(redirect.from)) throw new Error(`Duplicate or circular redirect source: ${redirect.from}`);
  seen.add(redirect.from);
}
const generated = ["# Generated from src/data/redirects.json. Do not edit this file directly.", ...redirects.map(({ from, to, status }) => `${from} ${to} ${status}`), ""].join("\n");
await writeFile(outputUrl, generated);
console.log(`Generated ${redirects.length} redirects from the authoritative registry.`);
